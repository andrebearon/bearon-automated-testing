const { chromium } = require('@playwright/test');
const h = require('./tests/helpers');
(async () => {
  const proxy = process.env.PLAYWRIGHT_PROXY ? { server: process.env.PLAYWRIGHT_PROXY } : undefined;
  const browser = await chromium.launch({ headless: true, proxy });
  const context = await browser.newContext({ baseURL: 'https://bearon.studio', storageState: 'auth/.storage-state.json', ignoreHTTPSErrors: Boolean(process.env.PLAYWRIGHT_PROXY) });
  const page = await context.newPage();
  await h.ensureWorkspace(page);
  await page.goto('/console/pos/dashboard/pos/cash-register/');
  await page.getByRole('button', { name: 'All Logs' }).click();
  await page.waitForTimeout(2500);
  console.log('=== ALL LOGS (first 2000) ===');
  console.log((await page.locator('body').innerText()).slice(0, 2000));
  console.log('URL:', page.url());
  await page.goto('/console/pos/dashboard/pos/cash-register/');
  await page.waitForTimeout(2000);
  await page.getByRole('button', { name: 'Close session' }).click();
  await page.waitForTimeout(2500);
  console.log('=== CLOSE SESSION DIALOG (first 2200) ===');
  console.log((await page.locator('body').innerText()).slice(0, 2200));
  console.log('INPUTS:', JSON.stringify(await page.locator('input').evaluateAll(els => els.map(e => ({ name: e.getAttribute('name'), placeholder: e.getAttribute('placeholder'), type: e.type, value: e.value })))));
  await browser.close();
})().catch(e => { console.error('PROBE-FAIL:', e.message.slice(0, 400)); process.exit(1); });
